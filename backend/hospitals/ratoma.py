"""
Health facilities of the commune of Ratoma (Conakry, Guinée) used to pre-fill the list.

ONLY facilities whose name AND commune are documented by a public source are listed, and only what the
sources state is recorded: name, type and (when stated) the quartier. No phone number, no street address and
no contact person is invented. THE MAIRIE MUST VALIDATE THIS LIST (add, rename, deactivate) from the screen
« Hôpitaux et maternités ».

Sources (read in November 2026):
- OMS Afrique, « Le Représentant de l'OMS visite le Centre médico-communal de Ratoma » — CMC de Ratoma,
  commune de Ratoma, with a maternity ward (https://afro.who.int/node/4973).
- Wikipédia « CMC Flamboyant » — « Le centre médical communal Les Flamboyants … situé dans la commune de
  Ratoma », public, with a maternity (https://fr.wikipedia.org/wiki/CMC_Flamboyant).
- Guinéenews, « HASIGUI, le fleuron de la coopération sanitaire sino-guinéenne » (2024) — Hôpital de
  l'Amitié Sino-Guinéenne, quartier Kipé, commune de Ratoma
  (https://guineenews.org/2024/11/04/hasigui-le-fleuron-de-la-cooperation-sanitaire-sino-guineenne/).
- Comité national de lutte contre le sida, « Sites de prise en charge (PEC) et contacts des responsables »
  (2019) — structures classées dans la commune de Ratoma : Hôpital Jean-Paul II, Clinique Aimé, centres de
  santé de Wanindara et de Lambanyi (https://cnls-guineeconakry.org/wp-content/uploads/2019/09/SITES-PEC-ET-CONTACT-DES-RESPONSABLES.pdf).

Left out on purpose because the sources do not allow a safe name or location: « Centre Mère-Enfant » and
« FMG » (CNLS list), and Clinique Ambroise Paré (Corniche, commune de Dixinn — not Ratoma).
"""
from audit import service as audit
from audit.models import AuditAction

from .models import Hospital

RATOMA_FACILITIES = [
    {'name': 'Centre Médical Communal (CMC) de Ratoma', 'facility_type': Hospital.FacilityType.HEALTH_CENTER},
    {'name': 'Centre Médical Communal Les Flamboyants', 'facility_type': Hospital.FacilityType.HEALTH_CENTER},
    {'name': "Hôpital de l'Amitié Sino-Guinéenne", 'facility_type': Hospital.FacilityType.HOSPITAL, 'address': 'Kipé'},
    {'name': 'Hôpital Jean-Paul II', 'facility_type': Hospital.FacilityType.HOSPITAL},
    {'name': 'Clinique Aimé', 'facility_type': Hospital.FacilityType.CLINIC},
    {'name': 'Centre de santé de Wanindara', 'facility_type': Hospital.FacilityType.HEALTH_CENTER, 'address': 'Wanindara'},
    {'name': 'Centre de santé de Lambanyi', 'facility_type': Hospital.FacilityType.HEALTH_CENTER, 'address': 'Lambanyi'},
]


def prefill_ratoma_facilities():
    """
    Create the facilities of ``RATOMA_FACILITIES`` that do not exist yet (compared by name, ignoring case and
    including archived ones, so a facility the administrator archived is never recreated).
    Returns ``(created, skipped)`` lists of names. Codes (WH-0001-26) are generated by the server.
    """
    created, skipped = [], []
    for spec in RATOMA_FACILITIES:
        if Hospital.all_objects.filter(name__iexact=spec['name']).exists():
            skipped.append(spec['name'])
            continue
        hospital = Hospital(
            name=spec['name'], facility_type=spec['facility_type'], region='Conakry', commune='Ratoma',
            address=spec.get('address', ''))
        hospital.save()
        audit.log(AuditAction.CREATE, obj=hospital,
                  changes=audit.snapshot(hospital, ['code', 'name', 'facility_type', 'region', 'commune', 'address']),
                  reason="Préremplissage des établissements de Ratoma (à valider par la mairie)")
        created.append(spec['name'])
    return created, skipped
